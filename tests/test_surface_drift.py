"""D-15 — the standing **documented-drift** gate on the public surface.

The committed manifest ``docs/surface/v0.2-surface.json`` must equal what
``tools/dump_surface.py`` emits right now, *or* every module whose entry moved
must be claimed by a ``docs/surface-changes/15-*.md`` fragment. This module
lives in ``tests/`` rather than in a bespoke CI job because ``tests/`` is the
already-always-on ``test`` job — so a surface change fails CI on the same
commit that causes it, with no new CI wiring (the reasoning transferred
verbatim from ``tests/http_api/test_openapi.py:9-14``).

Why documented-drift rather than bare bytes-equality
----------------------------------------------------

Phase 15 runs eleven waves of plans that each change the public surface, and
the live manifest is regenerated by exactly one plan at each end of the phase
— 15-01 at phase start, 15-21 at phase close. That single-owner rule is not a
convenience: a whole-tree file cannot be concurrently regenerated in eleven
worktrees without going stale after the second merge, on a file no plan then
owns. A gate that demanded bytes-equality throughout would therefore be red
for the whole phase and would get switched off, which is how gates die.

This formulation keeps the gate live and enforces the thing D-15 actually asks
for: **drift is permitted exactly when it is documented.** After 15-21
regenerates the live manifest, nothing is unclaimed and the assertion
degenerates back to bytes-equality with no code change.

Known limitation, by design
---------------------------

**This standing gate is a module-granular, direction-blind tripwire.**
Fragments accumulate and are read as a union, so once any plan names a module,
later drift in that same module is claimed for the rest of the phase —
including an export *removed* by a later plan, and including a fragment that
says ``added`` when the manifest actually shows ``removed``. That is acceptable
for a tripwire whose job is to catch someone widening the surface with no
fragment at all.

**Name-level and direction-level completeness is guaranteed elsewhere**, by
``tests/test_surface_completeness.py`` in plan 15-21, which diffs the frozen
``docs/surface/v0.2-surface-baseline.json`` against the final live manifest at
fully-qualified-name granularity and asserts a matching ``docs/SURFACE-CHANGES.md``
entry with a matching change type, in **both** directions. **The two are
designed as a pair**: the standing gate is cheap and always-on during the
phase; the cross-check is exact and runs once at phase close. Neither is
sufficient alone, and weakening either without the other is a regression.

Claims are matched by **literal substring** of the fully-qualified name, with
the dotted module name as the fallback — never by parsing the fragment. The
fragment's ``Surface`` field is required to carry the fully dotted name
(``docs/surface-changes/README.md``), so a literal match is sufficient and
cannot rot against a Markdown reformat.
"""

from __future__ import annotations

import json
import pathlib
from typing import Any

from tools.assemble_surface_changes import (
    OUTPUT_PATH as _CURATED_LOG,
)
from tools.assemble_surface_changes import (
    REGENERATION_COMMAND as _ASSEMBLE_COMMAND,
)
from tools.assemble_surface_changes import (
    serialize as serialize_curated_log,
)
from tools.dump_surface import build_surface, diff_surfaces, serialize

# Repo root from this file's own path, never ``Path.cwd()`` — pytest may be
# invoked from anywhere and the manifest is a fixed repo artifact.
_REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]

#: The **live** manifest — deliberately the unqualified name, so that whoever
#: reaches for "the surface manifest" gets the current surface.
_LIVE_MANIFEST = _REPO_ROOT / "docs" / "surface" / "v0.2-surface.json"

#: The frozen phase-start copy, written once by plan 15-01 and never again.
_FROZEN_BASELINE = (
    _REPO_ROOT / "docs" / "surface" / "v0.2-surface-baseline.json"
)

_FRAGMENT_DIR = _REPO_ROOT / "docs" / "surface-changes"

_DRIFT_MESSAGE = (
    "The public surface drifted from the committed"
    " docs/surface/v0.2-surface.json and no surface-change fragment claims"
    " it. Either run `make surface` and commit the result (phase start /"
    " phase close only — the live manifest has a single owner at each end of"
    " Phase 15), or write a docs/surface-changes/15-NN-<slug>.md fragment"
    " naming what changed and why. A removed export or a Pydantic version"
    " bump legitimately changes the public surface — that diff is reviewable"
    " and desirable, not a test bug."
)


def _fragment_text() -> str:
    """Every ``15-*.md`` fragment concatenated — claims are read as a union."""
    if not _FRAGMENT_DIR.is_dir():
        return ""
    return "\n".join(
        path.read_text(encoding="utf-8")
        for path in sorted(_FRAGMENT_DIR.glob("15-*.md"))
    )


def unclaimed_drift(
    committed: dict[str, Any], live: dict[str, Any], claims: str
) -> list[str]:
    """Drifting names that no fragment claims.

    A drifting fully-qualified name is claimed when either the name itself or
    its dotted module appears literally in the fragment text. The module-level
    fallback is what makes this gate module-granular; see the module docstring
    for why that is deliberate and where the exact guarantee lives.
    """
    difference = diff_surfaces(committed, live)
    drifting = sorted(
        set(difference["added"])
        | set(difference["removed"])
        | set(difference["reshaped"])
    )
    unclaimed: list[str] = []
    for qualified in drifting:
        module = qualified.rsplit(".", 1)[0]
        if qualified in claims or module in claims:
            continue
        unclaimed.append(qualified)
    return unclaimed


def test_surface_drift_is_absent_or_documented() -> None:
    """D-15: the committed manifest is either current or explained.

    The no-drift case is asserted on **bytes**, not on parsed dicts, because
    the committed file is reviewed as a diff — whitespace and key order are
    part of what makes that diff readable, so they are part of what is
    asserted.
    """
    live_document = build_surface()
    committed_bytes = _LIVE_MANIFEST.read_text(encoding="utf-8")
    if committed_bytes == serialize(live_document):
        return

    committed_document = json.loads(committed_bytes)
    unclaimed = unclaimed_drift(
        committed_document, live_document, _fragment_text()
    )
    assert not unclaimed, f"{_DRIFT_MESSAGE}\nUnclaimed: {unclaimed}"


def test_the_drift_message_names_its_own_fix() -> None:
    """Edge case: a failure nobody can act on is a failure that gets muted."""
    assert "make surface" in _DRIFT_MESSAGE
    assert "v0.2-surface.json" in _DRIFT_MESSAGE
    assert "docs/surface-changes/" in _DRIFT_MESSAGE


def test_the_committed_manifest_is_non_vacuous() -> None:
    """A discovery helper that silently found nothing is the quietest way
    this gate stops being one."""
    document = json.loads(_LIVE_MANIFEST.read_text(encoding="utf-8"))
    assert len(document) >= 50, len(document)
    for module in (
        "ccf.controlplane.artifacts",
        "ccf.boot",
        "ccf.products.gates",
    ):
        assert module in document, module


def test_a_fragment_claim_admits_the_drift_it_names() -> None:
    """The gate is documented-drift, not a weakened bytes check.

    Exercised on hand-built manifests so the assertion is about the *rule*,
    not about whatever the tree happens to look like today.
    """
    before = {"m.a": {"exports": {"x": {"kind": "function", "shape": "()"}}}}
    after = {"m.a": {"exports": {"x": {"kind": "function", "shape": "(y)"}}}}

    assert unclaimed_drift(before, after, "") == ["m.a.x"]
    assert unclaimed_drift(before, after, "Surface: m.a.x") == []
    # module-granular fallback — the documented limitation, asserted
    assert unclaimed_drift(before, after, "Surface: m.a") == []
    # an unrelated claim does not admit it
    assert unclaimed_drift(before, after, "Surface: m.b.q") == ["m.a.x"]


def test_no_export_resolves_to_nothing() -> None:
    """The manifest must not depend on what the process imported first.

    A package listing submodules in ``__all__`` only binds them as attributes
    once something imports them, so a bare ``getattr`` records ``NoneType``
    when ``build_surface`` runs alone and ``module`` when the full suite has
    already pulled the submodule in — drift with no source change. A
    ``NoneType`` shape is the fingerprint of that failure mode, and there is
    no legitimate reason for a declared export to resolve to nothing.
    """
    document = json.loads(_LIVE_MANIFEST.read_text(encoding="utf-8"))
    unresolved = [
        f"{module}.{name}"
        for module, record in document.items()
        for name, entry in record["exports"].items()
        if entry["shape"] == "NoneType"
    ]
    assert not unresolved, unresolved


def test_the_curated_log_is_assembled_from_the_current_fragments() -> None:
    """D-15's curated half: a fragment added without reassembly is a red build.

    The generated manifest and the curated log are two halves of one
    guarantee, so the log needs a standing staleness gate of its own. Without
    it, a plan could write a fragment, never run ``make surface-changes``, and
    ship a migration note that silently omits its change — the one failure
    ``docs/SURFACE-CHANGES.md`` cannot afford, because Phase 16 consumes it
    directly.

    Asserted on **bytes** against the exported ``serialize``, on the same
    reasoning as the manifest above: the committed document is reviewed as a
    diff, so its exact rendering is part of what is asserted, and importing
    the assembler's own recipe means the file and this assertion cannot
    disagree about what "the log" is.
    """
    assert _CURATED_LOG.is_file(), (
        f"{_CURATED_LOG} is missing. Run `{_ASSEMBLE_COMMAND}`."
    )
    assert _CURATED_LOG.read_text(encoding="utf-8") == serialize_curated_log(), (
        f"{_CURATED_LOG} differs from what the fragments under"
        f" {_FRAGMENT_DIR} assemble to. Run `{_ASSEMBLE_COMMAND}` and commit"
        " the result."
    )


def test_the_frozen_baseline_exists_and_is_non_vacuous() -> None:
    """The immutable "before" side of ROADMAP Success Criterion 6.

    Only existence, validity, and non-vacuity are asserted. Byte-identity
    with the live manifest holds at phase start and is *expected* to stop
    holding the moment the first Phase 15 surface change lands — asserting it
    here would write a test 15-02 must immediately delete.
    """
    assert _FROZEN_BASELINE.is_file(), _FROZEN_BASELINE
    document = json.loads(_FROZEN_BASELINE.read_text(encoding="utf-8"))
    assert len(document) >= 50, len(document)

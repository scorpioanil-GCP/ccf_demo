"""The typed approval policy — WHO may approve a gate (SEC-006; `D-IMPL-366`).

SDK-defined mechanism (CLAUDE.md §8.2; §6.4 No-Hardcoding). Until this class
existed, every ``gate_policies`` target in the tree was an untyped
``DeclaredArtifact`` whose ``approver_role`` and ``quorum`` no code read, so
"who may approve" was a documented intent and not a control (the finding).
:class:`ApprovalPolicy` is the contract the SDK judges against, at every site a
human verdict can enter the authority path — the transport, the primitive and
the engine (``check_approver_eligibility`` in :mod:`ccf.hitl.transport`).

**What the policy carries (RULED, brief §1).** ``eligible_principals`` — the
set of ``subject_id`` strings permitted to approve, principal-based, the same
axis :class:`~ccf.hitl.transport.HitlPolicy` keys its trusted keys by
(`D-IMPL-366` G4 (a)) — and nothing else: no ``self_approval_permitted`` switch
(requester ≠ approver is unconditional whenever a policy is bound), no
``quorum`` (one eligible verdict routes; two agreeing verdicts still route), no
``eligible_roles`` (roles are a `D-IMPL-366` §9 follow-on). An **empty** set is
a policy nobody can satisfy and is refused at construction, by name (G7 (a)).
The policy carries principal strings only — never keys or secrets (CINV-01).

**Adopter-registered, not manifest-addressable (RULED).** Like
``ccf.hitl-policy``, the class is registered by adopter code through
``register_typed`` against :data:`APPROVAL_POLICY` and is deliberately absent
from :data:`ccf.deployment.classes.SDK_ARTIFACT_CLASSES`, so a deployment
manifest cannot name it (D-IMPL-84 refuses the reserved prefix). A gate event
pins the policy by ``ccf-artifact://`` URI at suspension, and the eligibility
helper resolves exactly that pinned version — never "latest" — so the version
that judged an approval is the version the event named (replayable).

The JSON schema is ``docs/schemas/ccf.approval-policy.json``, generated by
``tools/dump_schemas.py`` from this contract.
"""

from __future__ import annotations

from pydantic import Field, field_validator

from ccf.contracts.base import CCFContract
from ccf.controlplane.artifact_base import ArtifactClass, validate_semver

__ccf_mode__ = "algorithmic"

__all__ = ["APPROVAL_POLICY", "ApprovalPolicy"]


class ApprovalPolicy(CCFContract):
    """Who may approve a gate: a non-empty set of eligible ``subject_id``s.

    A deployment registers one per gate (or shares one across gates) and pins
    it from the workflow definition's ``gate_policies``:
    ``{semver: "1.0.0", eligible_principals: ["officer-a", "officer-b"]}``.

    Attributes:
        semver: The artifact's own semver lane (whitepaper §6.3).
        eligible_principals: The ``subject_id`` strings permitted to approve a
            gate bound to this policy. Never empty (`D-IMPL-366` G7 (a)); never
            compared against the requester's favor — the requester is refused
            even when listed (SPEC F3, RULED).
    """

    semver: str
    eligible_principals: frozenset[str] = Field(min_length=1)

    @field_validator("semver")
    @classmethod
    def _semver_is_well_formed(cls, value: str) -> str:
        return validate_semver(value)

    @field_validator("eligible_principals")
    @classmethod
    def _eligible_principals_are_named(cls, value: frozenset[str]) -> frozenset[str]:
        if not value:
            raise ValueError(
                "eligible_principals is empty: a policy nobody can satisfy is"
                " refused at construction rather than registered to refuse every"
                " approver at runtime (D-IMPL-366 G7 (a); SEC-006)"
            )
        if any(not principal.strip() for principal in value):
            raise ValueError(
                "eligible_principals contains an empty or whitespace-only"
                " subject_id; an unnamed principal can never present a"
                " capability and is refused at construction (D-IMPL-366; CINV-01)"
            )
        return value


#: The approval-policy artifact class (SEC-006; `D-IMPL-366` §4 (1), SPEC F1).
#: Adopter-registered only; NOT in ``SDK_ARTIFACT_CLASSES`` by ruling.
APPROVAL_POLICY = ArtifactClass(class_id="ccf.approval-policy", contract=ApprovalPolicy)

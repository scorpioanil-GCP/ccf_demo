def test_the_confirmed_probe_workflow_is_refused_on_all_three_steps() -> None:
    text = (
        "on: push\npermissions:\n  contents: read\njobs:\n  j:\n    runs-on: x\n    steps:\n"
        "      - run: pip -q install -e \".[dev]\"\n"
        "      - run: pip3.12 install -e .\n"
        "      - run: uv sync\n"
    )
    assert len(lint.check_workflow(text, "w.yml")) == 3


def test_a_redirection_does_not_split_a_command() -> None:
    assert lint.commands("pip install x 2>&1 | tee log") == ["pip install x 2>&1", "tee log"]


def test_a_multi_line_run_block_is_split_per_command() -> None:
    text = (
        "on: push\npermissions:\n  contents: read\njobs:\n  j:\n    runs-on: x\n    steps:\n"
        "      - run: |\n"
        "          python -m venv .venv\n"
        "          .venv/bin/pip install --require-hashes -r requirements.lock\n"
        "          .venv/bin/pip install -e . --no-deps && pip install -e x \\\n"
        "            --no-deps --no-build-isolation\n"
    )
    found = lint.check_workflow(text, "w.yml")
    assert len(found) == 1 and "missing `--no-build-isolation`" in found[0]


def test_a_makefile_recipe_is_checked_and_a_comment_is_not() -> None:
    assert lint.check_makefile('# pip install -e ".[dev]"\ninstall:\n\t@.venv/bin/pip install -e ".[dev]"\n')
    assert lint.check_makefile('# pip install -e ".[dev]"\nx:\n\techo ok\n') == []


def test_a_tree_that_is_not_a_project_has_no_finding(tmp_path: pathlib.Path) -> None:
    assert lint.check_tree(tmp_path) == []


def test_a_project_without_a_lock_is_refused(tmp_path: pathlib.Path) -> None:
    (tmp_path / "pyproject.toml").write_text("[project]\nname='x'\n")
    found = lint.check_tree(tmp_path)
    assert len(found) == 1 and "no `requirements.lock`" in found[0]


def test_the_lint_reads_the_same_workflows_as_ci_posture() -> None:
    assert [p.name for p in ci_posture.workflow_paths(REPO_ROOT)] == sorted(WORKFLOWS)



"""Generate the `cp-03` census fixture from the live estate.

**THE FIXTURE IS A SNAPSHOT, AND THIS IS THE COMMAND THAT TAKES IT.** Phase 24.3
criteria 2-12 re-derive eleven census figures — 321 restatement groups across 37
obligors, the 100/46/175 severity bands, the 8,088/6,967 instant-duration split,
Item 4.02's 9-of-37 overlap — and they must run **in CI, on every push**, not
only where the LAN estate is reachable. A census that runs when someone
remembers to run it is a check whose population is not its question, which is
the defect class this whole rung exists to catch.

So CI gets the WHOLE `financial_fact` population rather than a sample. A sampled
fixture would make every one of those gates assert something true of the sample
and nothing about the product.

**WHY THIS FILE EXISTS AT ALL.** `cp-02`'s fixture header says it was "GENERATED
FROM THE LIVE ESTATE ... not authored", and no generator was committed beside
it — so the claim could not be re-run. Dave, 2026-08-30: pin it "like any other
teaching snapshot: named file, generated by a documented command, not
hand-edited."

Usage, from the repository root, with `ccf_dataprep`'s `.env` reachable:

    PYTHONPATH=.:src:runtime .venv/bin/python tools/dump_cp03_fixture.py

**REFRESHING IS A DELIBERATE COMMIT**, on the same footing as changing an
`expected_output.txt`: run this, read the diff, and land it with the reason. It
is never a step on the demonstrated path, and the drift check in
`tests/examples/test_cp_03_census.py` **fails loudly rather than refreshing
anything** when the fixture and the live estate disagree.

Output is deterministic — every table is ordered by its own key — so re-running
against an unchanged estate produces a byte-identical file and `git diff` is a
true drift report.
"""

from __future__ import annotations

import datetime
import pathlib
import sys

FIXTURES = pathlib.Path(__file__).resolve().parents[1] / "tests" / "examples" / "fixtures"

#: The tables the census reads, each with the ORDER BY that makes its dump
#: deterministic. `peer_fact` is deliberately absent: no criterion 2-12 touches
#: peers, and 22,494 more rows would triple the fixture to gate nothing.
TABLES: dict[str, str] = {
    "legal_entity": "lei",
    "crosswalk": "lei, internal_client_id",
    "filing_profile": "lei",
    "financial_fact": "lei, tag, unit, period_end, fiscal_period, accession",
}


def _connect():
    from dotenv import dotenv_values
    import psycopg

    env = dotenv_values("/home/parkave/ccf_dataprep/.env")
    dsn = (
        f"host={env.get('PGHOST', '192.168.4.76')} port={env.get('PGPORT', '5432')} "
        f"dbname={env.get('PGDATABASE', 'parkavedb')} user={env.get('PGUSER', 'parkave')} "
        f"password={env.get('PGPASSWORD')}"
    )
    return psycopg.connect(dsn), env.get("PG_SCHEMA_V2", "ccf_v2")


def _ddl(cur, schema: str, table: str) -> str:
    """Column-for-column, type-for-type, from `information_schema` — not transcribed."""
    cur.execute(
        """SELECT column_name, data_type, character_maximum_length, is_nullable
             FROM information_schema.columns
            WHERE table_schema = %s AND table_name = %s
            ORDER BY ordinal_position""",
        (schema, table),
    )
    columns = []
    for name, kind, length, nullable in cur.fetchall():
        rendered = f"character({length})" if kind == "character" and length else kind
        columns.append(f"    {name} {rendered}{'' if nullable == 'YES' else ' NOT NULL'}")
    return f"CREATE TABLE {schema}.{table} (\n" + ",\n".join(columns) + "\n);"


def _literal(value: object) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return str(value)
    text = str(value).replace("'", "''")
    return f"'{text}'"


def main() -> int:
    connection, schema = _connect()
    stamp = datetime.date.today().isoformat()
    with connection:
        connection.read_only = True
        with connection.cursor() as cur:
            ddl = [_ddl(cur, schema, table) for table in TABLES]
            (FIXTURES / "cp_03_census_schema.sql").write_text(
                f"-- The CI container's schema for `examples/cp-03-obligor-financial-spread`.\n"
                f"--\n"
                f"-- GENERATED by `tools/dump_cp03_fixture.py` on {stamp}, column for column\n"
                f"-- and type for type from `{schema}`'s own `information_schema` rather than\n"
                f"-- hand-transcribed. The SCHEMA NAME matches the real estate's, so the\n"
                f"-- example's own queries run unchanged against the container.\n\n"
                f"CREATE SCHEMA IF NOT EXISTS {schema};\n\n" + "\n\n".join(ddl) + "\n",
                encoding="utf-8",
            )

            body: list[str] = []
            counts: dict[str, int] = {}
            for table, order in TABLES.items():
                cur.execute(f"SELECT * FROM {schema}.{table} ORDER BY {order}")
                names = [d.name for d in cur.description]
                rows = cur.fetchall()
                counts[table] = len(rows)
                body.append(f"-- {table}: {len(rows)} rows")
                # BATCHED, and the batching is not cosmetic. One INSERT per row
                # repeats the column list 15,055 times and produced a 6.4 MB
                # file; naming the columns once per batch is the same SQL,
                # applied by the same single `cursor.execute`, at a third the
                # size. 500 keeps any one statement readable in a diff.
                header = f"INSERT INTO {schema}.{table} ({', '.join(names)}) VALUES"
                for start in range(0, len(rows), 500):
                    batch = rows[start : start + 500]
                    tuples = [
                        "  (" + ", ".join(_literal(v) for v in row) + ")" for row in batch
                    ]
                    body.append(header)
                    body.append(",\n".join(tuples) + ";")
                body.append("")

            census = (
                f"-- Rows for `examples/cp-03-obligor-financial-spread`, seeded by\n"
                f"-- `tests/examples/test_cp_03_census.py` and by nothing else.\n"
                f"--\n"
                f"-- GENERATED FROM THE LIVE ESTATE on {stamp} by\n"
                f"-- `tools/dump_cp03_fixture.py`, not authored. Re-running against an\n"
                f"-- unchanged estate reproduces this file byte for byte, so `git diff` on\n"
                f"-- it is a true drift report.\n"
                f"--\n"
                f"-- THE WHOLE `financial_fact` POPULATION IS HERE rather than a sample,\n"
                f"-- because criteria 2-12 assert exact census figures and a sampled fixture\n"
                f"-- would make every one of them true of the sample and silent about the\n"
                f"-- product. `peer_fact` is absent: no census criterion touches peers.\n"
                f"--\n"
                f"-- NO NUMBER HERE IS A FACT ABOUT ANY REAL COMPANY'S FINANCIALS. The LEIs\n"
                f"-- and CIKs are real identifiers; the figures are `ccf_dataprep`'s\n"
                f"-- educational estate.\n\n" + "\n".join(body)
            )
            (FIXTURES / "cp_03_census_rows.sql").write_text(census, encoding="utf-8")

    for table, n in counts.items():
        print(f"  {table:18s} {n:6d} rows")
    size = (FIXTURES / "cp_03_census_rows.sql").stat().st_size
    print(f"  wrote cp_03_census_rows.sql   {size / 1024:.0f} KB")
    print(f"  wrote cp_03_census_schema.sql {(FIXTURES / 'cp_03_census_schema.sql').stat().st_size / 1024:.0f} KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

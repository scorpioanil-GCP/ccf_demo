def _literal(value: object) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return str(value)
    text = str(value).replace("'", "''")
    return f"'{text}'"


def _dump_postgres(dsn: str, leis: list[str], stamp: str) -> int:
    """Emit the schema and the rows the family graph's LEIs resolve to."""
    import psycopg

    with psycopg.connect(dsn, connect_timeout=15) as connection:
        connection.read_only = True
        with connection.cursor() as cursor:
            # Column for column and type for type from the estate's own
            # `information_schema`, never hand-transcribed.
            cursor.execute(
                """SELECT column_name, data_type, character_maximum_length, is_nullable
                     FROM information_schema.columns
                    WHERE table_schema = %s AND table_name = %s
                    ORDER BY ordinal_position""",
                (SOURCE_SCHEMA, ATTRIBUTE_TABLE),
            )
            columns = []
            for name, kind, length, nullable in cursor.fetchall():
                rendered = f"character({length})" if kind == "character" and length else kind
                columns.append(f"    {name} {rendered}{'' if nullable == 'YES' else ' NOT NULL'}")
            if not columns:
                raise SystemExit(
                    f"{SOURCE_SCHEMA}.{ATTRIBUTE_TABLE} has no columns in "
                    f"information_schema — the DSN is pointed somewhere without it."
                )

            # ONLY the rows that exist. The 39 family LEIs with no row must be
            # GENUINELY ABSENT rather than present-and-null: criterion 12
            # asserts 20 of 22 subtree nodes resolve to NO Postgres row, and a
            # null-filled placeholder row would make that assertion false while
            # every count still looked right.
            cursor.execute(
                f"SELECT * FROM {SOURCE_SCHEMA}.{ATTRIBUTE_TABLE} "
                f"WHERE lei = ANY(%s) ORDER BY lei",
                (leis,),
            )
            names = [d.name for d in cursor.description]
            rows = cursor.fetchall()

    table = f"{SCHEMA_PLACEHOLDER}.{ATTRIBUTE_TABLE}"
    schema_sql = (
        f"-- The CI container's schema for `examples/cp-04-corporate-family-tree`.\n"
        f"--\n"
        f"-- GENERATED by `tools/dump_cp04_fixture.py` on {stamp}, column for column\n"
        f"-- and type for type from the estate's own `information_schema` rather than\n"
        f"-- hand-transcribed.\n"
        f"--\n"
        f"-- THE SCHEMA NAME IS A PARAMETER, spelled `{SCHEMA_PLACEHOLDER}`, and it is\n"
        f"-- substituted by `tests/examples/cp_04_seed.py`. Six cp-04 test modules seed\n"
        f"-- this one fixture against a SESSION-SCOPED `postgres_dsn`, whose own\n"
        f"-- docstring says isolation comes from a fresh SCHEMA rather than a fresh\n"
        f"-- server. A fixed schema name here would put all six in one, where whichever\n"
        f"-- ran first leaves its tables for the second -- the `leg-postgres` collision\n"
        f"-- this repository has already shipped red on `main`.\n\n"
        f"CREATE SCHEMA IF NOT EXISTS {SCHEMA_PLACEHOLDER};\n\n"
        f"DROP TABLE IF EXISTS {table} CASCADE;\n"
        f"CREATE TABLE {table} (\n" + ",\n".join(columns) + "\n);\n"
    )
    (FIXTURES / "cp_04_family_schema.sql").write_text(schema_sql, encoding="utf-8")

    body: list[str] = [f"-- {ATTRIBUTE_TABLE}: {len(rows)} rows"]
    header = f"INSERT INTO {table} ({', '.join(names)}) VALUES"
    for start in range(0, len(rows), 500):
        batch = rows[start : start + 500]
        body.append(header)
        body.append(
            ",\n".join("  (" + ", ".join(_literal(v) for v in row) + ")" for row in batch)
            + ";"
        )

    rows_sql = (
        f"-- Rows for `examples/cp-04-corporate-family-tree`, applied by\n"
        f"-- `tests/examples/cp_04_seed.py` and by nothing else.\n"
        f"--\n"
        f"-- GENERATED FROM THE LIVE ESTATE on {stamp} by\n"
        f"-- `tools/dump_cp04_fixture.py`, not authored. Re-running against an\n"
        f"-- unchanged estate reproduces this file byte for byte, so `git diff` on it\n"
        f"-- is a true drift report.\n"
        f"--\n"
        f"-- These are the rows the FAMILY GRAPH'S LEIs resolve to, and nothing else:\n"
        f"-- 181 of the 748 family nodes carry an `ex:lei` and {len(rows)} of those\n"
        f"-- resolve here. The ones that do NOT resolve are GENUINELY ABSENT rather\n"
        f"-- than present-and-null, because criterion 12 asserts 20 of 22 subtree\n"
        f"-- nodes resolve to no row at all.\n"
        f"--\n"
        f"-- The population is `{ATTRIBUTE_TABLE}` -- GLEIF Level 1 -- and NOT\n"
        f"-- `crosswalk`. The same 181 LEIs resolve 39 times there; a check reading\n"
        f"-- the wrong table returns a real number about the wrong thing.\n"
        f"--\n"
        f"-- The SCHEMA NAME IS A PARAMETER, spelled `{SCHEMA_PLACEHOLDER}`.\n\n"
        + "\n".join(body)
        + "\n"
    )
    (FIXTURES / "cp_04_family_rows.sql").write_text(rows_sql, encoding="utf-8")
    return len(rows)


# ---------------------------------------------------------------------------


def main() -> int:
    url = _require("CCF_CP_04_FLUREE_URL").rstrip("/")
    ledger = _require("CCF_CP_04_FLUREE_LEDGER")
    dsn = _require("CCF_CP_04_POSTGRES_DSN")
    stamp = datetime.date.today().isoformat()

    body, nodes = _dump_fluree(url, ledger, stamp)
    target = FIXTURES / "cp_04_family_fluree.json"
    target.write_text(
        json.dumps(body, indent=1, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )

    leis = sorted(
        {
            value
            for document in body["insert"]
            for value in document.get(LEI_P, [])
        }
    )
    resolved = _dump_postgres(dsn, leis, stamp)

    meta = body["_generated"]
    for name, count in meta["family_predicates"].items():
        print(f"  {name:28s} {count:6d} triples")
    print(f"  {'raw family triples':28s} {meta['raw_family_triples']:6d}")
    print(f"  {'nodes':28s} {len(nodes):6d}")
    print(f"  {'nodes carrying ex:lei':28s} {len(leis):6d}")
    print(f"  {'legal_entity rows written':28s} {resolved:6d}")
    print(f"  source ledger t at dump time: {meta['source_ledger_t']}")
    for name in ("cp_04_family_fluree.json", "cp_04_family_schema.sql", "cp_04_family_rows.sql"):
        print(f"  wrote {name:30s} {(FIXTURES / name).stat().st_size / 1024:8.0f} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())

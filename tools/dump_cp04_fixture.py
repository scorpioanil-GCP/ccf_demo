"""Generate the `cp-04` family-graph fixture from the live estate.

**THE FIXTURE IS A SNAPSHOT, AND THIS IS THE COMMAND THAT TAKES IT.** Phase
24.4 criteria 3-24 re-derive the corporate family graph — 636/140/140/103/36/3
family triples collapsing to 722 normalized parent->child edges over 748 nodes
and 83 roots, 181 LEI-bearing nodes of which 142 resolve in Postgres, two
`owns` cycles with exact rosters — and they must run **in CI, on every push**,
not only where the LAN estate is reachable. A census that runs when someone
remembers to run it is a check whose population is not its question.

So CI gets the WHOLE family subgraph rather than a sample. A sampled fixture
would make every one of those criteria assert something true of the sample and
nothing about the product.

**IT IS THE FAMILY SUBGRAPH, NOT A MIRROR.** The estate holds 91 classes and
171 predicates; this fixture carries the six family predicates, every node
either end of one of them reaches, and the three node attributes the criteria
read — `rdf:type`, `rdfs:label` and `ex:lei`. Nothing else. The other 165
predicates answer no cp-04 question and a fixture sized by the store rather
than by the question is how a 6 MB transaction budget gets spent on nothing.

**Direction is preserved as STORED, not as normalized.** `owns` and `controls`
are stored parent->child; the four consolidation and ultimate-parent predicates
are stored child->parent. The fixture reproduces the estate's own orientation,
because criterion 6's control REVERSES a predicate and asserts the root count
moves — and a fixture that had already normalized the arrows would make that
control unable to fire.

**WHY THIS FILE EXISTS AT ALL.** `cp-02`'s fixture header claimed it was
"GENERATED FROM THE LIVE ESTATE ... not authored" with no generator committed
beside it, so the claim could not be re-run. Dave, 2026-08-30: pin it "like any
other teaching snapshot: named file, generated by a documented command, not
hand-edited." `tools/dump_cp03_fixture.py` is the precedent this file follows.

Usage, from the repository root, with the estate reachable:

    CCF_CP_04_FLUREE_URL=...   \
    CCF_CP_04_FLUREE_LEDGER=...  \
    CCF_CP_04_POSTGRES_DSN=...   \
    PYTHONPATH=.:src:runtime .venv/bin/python tools/dump_cp04_fixture.py

**NO HOST, PORT, PATH OR CREDENTIAL LIVES IN THIS SOURCE.** All three come from
the environment, and the tool refuses to run rather than falling back to a
default — a default connection string is how a dump aimed at one estate
silently reads another.

**REFRESHING IS A DELIBERATE COMMIT**, on the same footing as changing an
`expected_output.txt`: run this, read the diff, and land it in the same
reviewed commit as the figures it moves. It is never run by a test and never
an automatic refresh; the drift between fixture and estate is a report, not a
thing to heal silently.

Output is deterministic — every collection is sorted by its own key and JSON is
rendered with sorted keys — so re-running against an unchanged estate produces
byte-identical files and `git diff` is a true drift report.
"""

from __future__ import annotations

import datetime
import json
import os
import pathlib
import sys
from typing import Any

import httpx

FIXTURES = pathlib.Path(__file__).resolve().parents[1] / "tests" / "examples" / "fixtures"

#: The schema the estate's `legal_entity` lives in, and the schema name the
#: example's own SQL is written against. It is a NAMESPACE, not connection
#: material: no host, no port, no credential. The emitted fixture does not
#: inherit it — see :data:`SCHEMA_PLACEHOLDER`.
SOURCE_SCHEMA = os.environ.get("CCF_CP_04_POSTGRES_SCHEMA", "ccf_v2")

#: The token the emitted SQL carries where a schema name would otherwise be
#: baked in. `tests/conftest.py` makes `postgres_dsn` session-scoped and says
#: isolation comes from a fresh SCHEMA rather than a fresh server, and SIX
#: cp-04 test modules seed this one fixture. A fixture naming one fixed schema
#: would put all six in the same one, where whichever ran first would leave its
#: tables behind for the second — the `leg-postgres` collision this repository
#: has already shipped red on `main`.
SCHEMA_PLACEHOLDER = "{schema}"

FIBO = "https://spec.edmcouncil.org/fibo/ontology/"
EX = "http://example.org/fibo/"

#: The six family predicates, full IRI -> short name, and the ORIENTATION each
#: is stored in. `True` means the stored subject is the parent.
#:
#: The direction is not cosmetic and it is not derivable from a count.
#: `ccf_dataprep/validators/test_parent_edge_direction.py` exists because 139
#: GLEIF edges were stored inverted for seven waves with every check green:
#: *"a count cannot see an arrow."*
FAMILY_PREDICATES: dict[str, tuple[str, bool]] = {
    FIBO + "FND/OwnershipAndControl/Ownership/owns": ("owns", True),
    FIBO + "FND/Relations/Relations/controls": ("controls", True),
    FIBO + "BE/LegalEntities/LEIEntities/isDirectlyConsolidatedBy": (
        "isDirectlyConsolidatedBy",
        False,
    ),
    FIBO + "BE/LegalEntities/LEIEntities/isUltimatelyConsolidatedBy": (
        "isUltimatelyConsolidatedBy",
        False,
    ),
    FIBO + "BE/OwnershipAndControl/CorporateControl/hasGlobalUltimateParent": (
        "hasGlobalUltimateParent",
        False,
    ),
    FIBO + "BE/OwnershipAndControl/CorporateControl/hasDomesticUltimateParent": (
        "hasDomesticUltimateParent",
        False,
    ),
}

LEI_P = EX + "lei"
LABEL_P = "http://www.w3.org/2000/01/rdf-schema#label"
TYPE_P = "http://www.w3.org/1999/02/22-rdf-syntax-ns#type"

#: The one Postgres table the cp-04 criteria resolve attributes from.
#:
#: **GLEIF Level 1, and it is NOT `crosswalk`.** Measured 2026-08-31: the same
#: 181 family LEIs resolve 142 times in `legal_entity` and 39 times in
#: `crosswalk`. Reading the wrong table produces a real number about the wrong
#: thing, which survives re-checking — the hazard this estate has already
#: produced once, inside CP-SPEC-003.
ATTRIBUTE_TABLE = "legal_entity"


def _require(name: str) -> str:
    value = os.environ.get(name)
    if not value:
        raise SystemExit(
            f"{name} is unset. This tool reads the LIVE estate and holds no "
            f"connection material in its source; it refuses to guess one, "
            f"because a defaulted endpoint is how a dump aimed at one estate "
            f"silently reads another."
        )
    return value



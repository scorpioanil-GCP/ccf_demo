def _sparql(client: httpx.Client, base: str, query: str) -> list[dict[str, Any]]:
    """Run one SPARQL SELECT and return its bindings.

    A `FROM <ledger>` clause is the caller's job: this server answers a query
    without one with an unhelpful HTTP 500 rather than a 400.
    """
    response = client.post(
        f"{base}/v1/fluree/query",
        headers={"Content-Type": "application/sparql-query"},
        content=query.encode("utf-8"),
    )
    response.raise_for_status()
    bindings: list[dict[str, Any]] = response.json()["results"]["bindings"]
    return bindings


def _pairs(client: httpx.Client, base: str, ledger: str, predicate: str) -> list[tuple[str, str]]:
    """ENUMERATE every `(subject, object)` for one predicate. Never an aggregate.

    Over this ledger the aggregate forms invent phantoms: `COUNT(DISTINCT ?p)`
    returns 178 and `GROUP BY ?p` returns 198 where `SELECT DISTINCT ?p`
    returns 171, which is the correct answer. Enumeration is the only form
    measured trustworthy here, and it is also the only form that can be
    written to a fixture.
    """
    query = f"SELECT ?s ?o FROM <{ledger}> WHERE {{ ?s <{predicate}> ?o }}"
    return [(b["s"]["value"], b["o"]["value"]) for b in _sparql(client, base, query)]


def _dump_fluree(url: str, ledger: str, stamp: str) -> tuple[dict[str, Any], list[str]]:
    """Build the transaction body, and return it with the ordered node roster."""
    with httpx.Client(timeout=120) as client:
        raw = {
            iri: _pairs(client, url, ledger, iri) for iri in sorted(FAMILY_PREDICATES)
        }
        # Node identity comes from the family edges themselves: a node is any
        # end of any family triple. Reading it from `rdf:type` instead would
        # pull in the whole 11,839-subject ledger.
        nodes = sorted({end for pairs in raw.values() for pair in pairs for end in pair})
        node_set = set(nodes)

        types: dict[str, list[str]] = {}
        for binding in _sparql(client, url, f"SELECT ?s ?o FROM <{ledger}> WHERE {{ ?s <{TYPE_P}> ?o }}"):
            subject = binding["s"]["value"]
            if subject in node_set:
                types.setdefault(subject, []).append(binding["o"]["value"])

        labels: dict[str, list[str]] = {}
        for binding in _sparql(client, url, f"SELECT ?s ?o FROM <{ledger}> WHERE {{ ?s <{LABEL_P}> ?o }}"):
            subject = binding["s"]["value"]
            if subject in node_set:
                labels.setdefault(subject, []).append(binding["o"]["value"])

        leis: dict[str, list[str]] = {}
        for binding in _sparql(client, url, f"SELECT ?s ?o FROM <{ledger}> WHERE {{ ?s <{LEI_P}> ?o }}"):
            subject = binding["s"]["value"]
            if subject in node_set:
                leis.setdefault(subject, []).append(binding["o"]["value"])

        ledger_t = _ledger_t(client, url, ledger)

    outgoing: dict[str, dict[str, list[str]]] = {}
    for predicate, pairs in raw.items():
        for subject, obj in pairs:
            outgoing.setdefault(subject, {}).setdefault(predicate, []).append(obj)

    documents: list[dict[str, Any]] = []
    for node in nodes:
        document: dict[str, Any] = {"@id": node}
        if node in types:
            document["@type"] = sorted(types[node])
        if node in labels:
            document[LABEL_P] = sorted(labels[node])
        if node in leis:
            document[LEI_P] = sorted(leis[node])
        for predicate, objects in sorted(outgoing.get(node, {}).items()):
            document[predicate] = [{"@id": o} for o in sorted(set(objects))]
        documents.append(document)

    body = {
        # `null` is deliberate and is the adapter's own setting: a default
        # `@context` — above all one carrying `@vocab` — silently changes what
        # every subsequent query matches while every write keeps succeeding.
        "@context": None,
        "_generated": {
            "by": "tools/dump_cp04_fixture.py",
            "on": stamp,
            "source_ledger": ledger,
            "source_ledger_t": ledger_t,
            "family_predicates": {
                FAMILY_PREDICATES[iri][0]: len(raw[iri]) for iri in sorted(raw)
            },
            "raw_family_triples": sum(len(v) for v in raw.values()),
            "nodes": len(nodes),
            "nodes_with_lei": len(leis),
            "note": (
                "The family subgraph of the source ledger, not a mirror of it. "
                "Predicate orientation is preserved AS STORED so criterion 6's "
                "reversal control can still fire. This block is provenance, not "
                "data: the server ignores unknown top-level keys, which is also "
                "why a seeder must verify readback rather than trust a 200."
            ),
        },
        "insert": documents,
    }
    return body, nodes


def _ledger_t(client: httpx.Client, base: str, ledger: str) -> int | None:
    """The source ledger's commit counter at dump time — provenance, not a pin.

    `t` is transaction time. It is recorded so a future reader can tell WHICH
    state this fixture was taken from; it does not back `as_of` (D-IMPL-88) and
    nothing here claims it pins a snapshot.
    """
    response = client.get(f"{base}/v1/fluree/ledgers")
    response.raise_for_status()
    name = ledger.split(":")[0]
    for entry in response.json():
        if entry.get("name") == name:
            value: int | None = entry.get("t")
            return value
    return None


